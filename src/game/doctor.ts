export interface Diagnosis {
  cause: Cause;
  score: number;
  label: 'чаще всего' | 'возможно' | 'реже';
}

/** Причины симптома по убыванию вероятности (с учётом вида и месяца). */
export function diagnose(symptomId: string, spId: string | null, month: number): { special?: string; list: Diagnosis[] } {
  const sym = SYMPTOM_BY_ID[symptomId];
  if (!sym) return { list: [] };
  const s = spId ? sp(spId) : null;
  const list = Object.entries(sym.causes)
    .map(([id, w]) => {
      const cause = CAUSES[id];
      return { cause, score: w * (s && cause.k ? cause.k(s, month) : 1) };
    })
    .sort((a, b) => b.score - a.score)
    .map((d, i, arr) => ({ ...d, label: (i === 0 ? 'чаще всего' : d.score >= arr[0].score * 0.55 ? 'возможно' : 'реже') as Diagnosis['label'] }));
  return { special: spId ? SPECIAL[spId]?.[symptomId] : undefined, list };
}
