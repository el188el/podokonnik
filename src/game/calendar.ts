/** Дела на месяц: общие сезонные и по видам из списка. */
export function careTasks(month: number, spIds: string[]): CareTask[] {
  const out = [...(SEASON[month] ?? [])];
  for (const id of [...new Set(spIds)]) {
    const t = SPECIAL[id]?.[month];
    if (t) out.push({ key: 'sp-' + id, icon: '🌿', text: t, sp: id });
  }
  return out;
}

