/** Короткая строка для бота: главное дело месяца для твоих растений. */
export function monthHeadline(month: number, spIds: string[]): string {
  const tasks = careTasks(month, spIds);
  const own = tasks.find((t) => t.sp);
  const t = own ?? tasks[0];
  if (!t) return '';
  return own ? `${sp(own.sp!).name}: ${own.text}` : t.text;
}

